"use client";

import { Tabs, TabsContent, TabsList, TabsTrigger } from "@paypal-seed/ui/components/tabs";
import { Check, Copy } from "lucide-react";
import { useState } from "react";
import type { Snippet } from "../content";

function CopyButton({ text }: { text: string }) {
  const [copied, setCopied] = useState(false);
  async function copy() {
    try {
      await navigator.clipboard.writeText(text);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      setCopied(false);
    }
  }
  return (
    <>
      <button
        type="button"
        onClick={copy}
        className="inline-flex min-h-11 items-center gap-1.5 rounded-full px-3 text-sm font-medium text-body transition-colors hover:bg-surface-strong hover:text-ink focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-ink"
      >
        {copied ? <Check aria-hidden="true" className="size-4" /> : <Copy aria-hidden="true" className="size-4" />}
        {copied ? "Copied" : "Copy"}
      </button>
      <span role="status" aria-live="polite" className="sr-only">
        {copied ? "Code copied to the clipboard" : ""}
      </span>
    </>
  );
}

export function CodeTabs({ snippets }: { snippets: ReadonlyArray<Snippet> }) {
  const [first] = snippets;
  if (!first) {
    return null;
  }
  return (
    <Tabs defaultValue={first.id} className="gap-0 overflow-hidden rounded-2xl border border-hairline bg-surface">
      <div className="flex flex-wrap items-center border-b border-hairline px-3 py-2">
        <TabsList aria-label="Language" variant="line" className="h-auto flex-wrap gap-1">
          {snippets.map((s) => (
            <TabsTrigger key={s.id} value={s.id} className="min-h-11 flex-none rounded-full px-4 text-[15px]">
              {s.label}
            </TabsTrigger>
          ))}
        </TabsList>
      </div>
      {snippets.map((s) => (
        <TabsContent key={s.id} value={s.id}>
          <div className="flex items-center justify-between gap-2 px-4 pt-2">
            {s.generated ? (
              <span className="rounded-full border border-hairline-strong px-2.5 py-1 text-xs font-medium text-body">
                Generated by APIMatic
              </span>
            ) : (
              <span className="text-xs text-muted-ink">Works anywhere</span>
            )}
            <CopyButton text={s.code} />
          </div>
          <pre
            tabIndex={0}
            className="overflow-x-auto px-4 pb-4 font-mono text-[13px] leading-relaxed text-ink focus-visible:outline-2 focus-visible:-outline-offset-2 focus-visible:outline-ink"
          >
            <code>{s.code}</code>
          </pre>
        </TabsContent>
      ))}
    </Tabs>
  );
}
